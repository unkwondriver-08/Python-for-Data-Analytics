# adding new elements in a new list using append() method
new_list = []

new_list.append('python')
new_list.append('java') 
print(new_list) #this will give you the list with the new elements added in it

#adding new elements in a new list using insert() method

new_list.insert(1, 'c++') #this will add the new element at index 1
print(new_list) #this will give you the list with the new elements added in it
