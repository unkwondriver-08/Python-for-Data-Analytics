
num1=1
num2=2.5

print(type(num1)) #this will give you the type of the variable
print(type(num2)) #this will give you the type of the variable
print(num1+num2) #this will give you the sum of the two variables
print(num1-num2) #this will give you the difference of the two variables
print(num1*num2) #this will give you the product of the two variables
print(num1/num2) #this will give you the quotient of the two variables
print(num1//num2) #this will give you the quotient of the two variables without the decimal part
print(num1%num2) #this will give you the remainder of the two variables
print(num1**num2) #this will give you the power of the two variables
print(abs(num1-num2)) #this will give you the absolute value of the difference of the two variables
print(round(num2)) #this will round the number to the nearest integer
print(round(2.89,1)) #this will round the number to the nearest integer with 1 decimal place


print(num1>num2) #this will give you a boolean value of whether num1 is greater than num2
print(num1 == num2) #this will give you a boolean value of whether num1 is equal to num2
print(num1 != num2) #this will give you a boolean value of whether num1 is not equal to num2
print(num1<=num2) #this will give you a boolean value of whether num1 is less than num2

#num1 =num2 is not same as num1 == num2, the first one is an assignment operator and the second one is a comparison operator
